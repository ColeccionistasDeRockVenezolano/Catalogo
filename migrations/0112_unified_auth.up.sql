-- La revocación pertenece a la base compartida, incluso si cambia la cuenta
-- un cliente distinto de Herra. Los incrementos explícitos existentes se conservan.
CREATE FUNCTION auth.revoke_changed_user() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.access_code_hash,NEW.status,NEW.project_id,NEW.name) IS DISTINCT FROM
     (OLD.access_code_hash,OLD.status,OLD.project_id,OLD.name) THEN
    NEW.session_version := greatest(NEW.session_version,OLD.session_version+1);
    UPDATE auth.admins SET session_version=session_version+1 WHERE user_id=OLD.id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER users_revoke_sessions BEFORE UPDATE ON auth.users
  FOR EACH ROW EXECUTE FUNCTION auth.revoke_changed_user();
CREATE FUNCTION auth.revoke_changed_admin() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.password_hash,NEW.role,NEW.project_id,NEW.user_id,NEW.username,NEW.mfa_enabled) IS DISTINCT FROM
     (OLD.password_hash,OLD.role,OLD.project_id,OLD.user_id,OLD.username,OLD.mfa_enabled) THEN
    NEW.session_version := greatest(NEW.session_version,OLD.session_version+1);
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER admins_revoke_sessions BEFORE UPDATE ON auth.admins
  FOR EACH ROW EXECUTE FUNCTION auth.revoke_changed_admin();
CREATE FUNCTION auth.revoke_changed_local() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.password_hash,NEW.role,NEW.enabled,NEW.username) IS DISTINCT FROM
     (OLD.password_hash,OLD.role,OLD.enabled,OLD.username) THEN
    NEW.session_version := greatest(NEW.session_version,OLD.session_version+1);
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER local_accounts_revoke_sessions BEFORE UPDATE ON auth.local_accounts
  FOR EACH ROW EXECUTE FUNCTION auth.revoke_changed_local();

