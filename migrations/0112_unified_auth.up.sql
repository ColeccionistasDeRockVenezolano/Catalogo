-- Compatibilidad de fechas UTC para los servicios síncronos de Herra.
CREATE FUNCTION auth.datetime(value text, modifier text DEFAULT NULL) RETURNS text
LANGUAGE sql STABLE AS $$
  SELECT to_char(timezone('UTC', CASE WHEN value = 'now' THEN statement_timestamp()
    ELSE value::timestamptz END) + coalesce(modifier::interval, interval '0'), 'YYYY-MM-DD HH24:MI:SS')
$$;

