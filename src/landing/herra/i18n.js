// Interpolación mínima: {clave} en el texto, valores ya escapados por quien
// llama cuando el resultado va dentro de HTML sin escapar.
function interpolate(template, vars) {
    if (!vars)
        return template;
    return template.replace(/\{(\w+)\}/g, (match, key) => (Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match));
}
const reportedMissing = new Set();
export function translate(lang, key, vars) {
    const entry = MESSAGES[key];
    if (!entry) {
        // Una clave inexistente no puede dejar la página en blanco: se devuelve la
        // propia clave —visible en la página, imposible de ignorar— y se registra
        // una sola vez para no inundar el log.
        if (!reportedMissing.has(key)) {
            reportedMissing.add(key);
            log.warn('i18n_missing_key', { key });
        }
        return key;
    }
    return interpolate(entry[lang] ?? entry[DEFAULT_LANG], vars);
}
export function translator(lang) {
    return (key, vars) => translate(lang, key, vars);
}
