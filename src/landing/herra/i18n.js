// Idioma de la interfaz — español e inglés.
//
// Dos capas independientes, deliberadamente:
//   1. Los textos fijos de Herra (navegación, roadmap, formularios, panel)
//      viven en el diccionario de este archivo.
//   2. Los textos propios de cada proyecto (nombre, portada, metadatos y
//      sección de apoyo) los escribe su administración en el panel y se
//      resuelven en project-i18n.ts.
//
// El idioma se negocia una vez por petición, en tres escalones: manda la
// cookie —una elección explícita del visitante—; si no hay, el idioma por
// defecto que su administración fijó al proyecto; y si ese ajuste es
// «sistema», el Accept-Language del navegador. Un navegador que no pide ni
// español ni inglés recibe inglés.
import { log } from './logger.js';
export const SUPPORTED_LANGS = ['es', 'en'];
export const DEFAULT_LANG = 'es';
// Idiomas que admiten traducción manual del contenido: todos menos el original.
// Lo usan las dos capas que se escriben a mano —los textos del proyecto y los
// de sus filas— para no repetir la misma resta en cada una.
export const TRANSLATABLE_LANGS = SUPPORTED_LANGS.filter(lang => lang !== DEFAULT_LANG);
// Un año: la preferencia de idioma no es una sesión, es una preferencia.
export const LANG_COOKIE_MAX_AGE_MS = 365 * 24 * 3600 * 1000;
export const LANG_SHORT_LABELS = { es: 'ES', en: 'EN' };
export const LANG_NAMES = { es: 'Español', en: 'English' };
export const OG_LOCALES = { es: 'es_ES', en: 'en_US' };
// Locale para fechas y números. La zona horaria sigue siendo la de la
// instancia: cambia el idioma de la interfaz, no dónde está el proyecto.
export const DATE_LOCALES = { es: 'es-VE', en: 'en-US' };
export function isLang(value) {
    return typeof value === 'string' && SUPPORTED_LANGS.includes(value);
}
// Accept-Language: «en-US,en;q=0.9,es;q=0.8». Se ordena por calidad y se toma
// el primer idioma que Herra hable, comparando solo la parte principal para
// que en-GB, en-US y en cuenten como el mismo inglés.
export function parseAcceptLanguage(header) {
    if (!header)
        return null;
    const entries = header.split(',')
        .map(part => {
        const [tag, ...params] = part.trim().split(';');
        const qParam = params.find(p => p.trim().startsWith('q='));
        const quality = qParam ? Number(qParam.trim().slice(2)) : 1;
        return { tag: tag.trim().toLowerCase(), quality: Number.isFinite(quality) ? quality : 0 };
    })
        .filter(entry => entry.tag !== '' && entry.quality > 0)
        .sort((a, b) => b.quality - a.quality);
    for (const entry of entries) {
        const base = entry.tag.split('-')[0];
        if (isLang(base))
            return base;
    }
    return null;
}
// Idioma por defecto de un proyecto, tal y como lo elige su administración:
// un idioma fijo, o 'system' para seguir al navegador de cada visitante.
export const PROJECT_LANG_MODES = [...SUPPORTED_LANGS, 'system'];
// Con 'system', un navegador que no pide ni español ni inglés recibe inglés:
// es la lengua franca, y quien no habla ninguna de las dos tiene más
// probabilidades de defenderse en ella que en español.
export const SYSTEM_FALLBACK_LANG = 'en';
export const PROJECT_DEFAULT_LANG_MODE = DEFAULT_LANG;
export function isProjectLangMode(value) {
    return typeof value === 'string' && PROJECT_LANG_MODES.includes(value);
}
// Idioma de una página de proyecto. Prioridad, de más a menos fuerte:
//   1. La cookie: el visitante pulsó el conmutador de idioma y esa elección
//      manda sobre cualquier ajuste del proyecto, ahora y en visitas futuras.
//   2. El idioma por defecto que su administración le fijó al proyecto.
//   3. Con 'system', el Accept-Language del navegador, y si no pide ninguno de
//      los dos idiomas, inglés.
export function detectLang(cookieValue, acceptLanguage, mode) {
    if (isLang(cookieValue))
        return cookieValue;
    if (isLang(mode))
        return mode;
    return parseAcceptLanguage(acceptLanguage) ?? SYSTEM_FALLBACK_LANG;
}
// Idioma de las páginas que no son de ningún proyecto —la portada con la lista
// y la superadministración—, donde no hay ajuste que respetar. Caen en español
// y no en inglés: son las páginas de Herra, no las de un proyecto, y el
// original de Herra está en español.
export function detectSiteLang(cookieValue, acceptLanguage) {
    if (isLang(cookieValue))
        return cookieValue;
    return parseAcceptLanguage(acceptLanguage) ?? DEFAULT_LANG;
}
